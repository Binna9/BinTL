type Widen<T> = T extends (...args: infer A) => string
  ? (...args: A) => string
  : T extends readonly (infer U)[]
    ? readonly Widen<U>[]
    : T extends object
      ? { [K in keyof T]: Widen<T[K]> }
      : T extends string
        ? string
        : T;

